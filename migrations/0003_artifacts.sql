-- 0003_artifacts.sql
-- Artifacts are first-class: metadata in Postgres, bytes in object storage.
-- A compound artifact (a web project, a repo tree) is ONE artifact row with
-- many artifact_files rows preserving the relative directory tree.

CREATE TABLE IF NOT EXISTS artifacts (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    slug               TEXT NOT NULL,
    title              TEXT NOT NULL,
    description        TEXT,
    artifact_type      TEXT NOT NULL DEFAULT 'other',
        -- web_project | code_project | document | dataset | image | video |
        -- audio | presentation | spreadsheet | archive | notebook | diagram | other
    source_type        TEXT NOT NULL,
        -- uploaded_by_user | generated_by_model | imported | external_reference
    source_provider    TEXT REFERENCES providers(id),
    source_conversation_id UUID REFERENCES conversations(id) ON DELETE SET NULL,
    source_message_id  UUID REFERENCES messages(id) ON DELETE SET NULL,
    project_id         UUID REFERENCES projects(id) ON DELETE SET NULL,
    storage_status     pc_storage_status NOT NULL DEFAULT 'referenced',
    classification_status pc_classification_status NOT NULL DEFAULT 'unclassified',
    sensitivity        pc_sensitivity NOT NULL DEFAULT 'normal',
    storage_prefix     TEXT,               -- server-generated object-key prefix
    vault_path         TEXT,
    version            INTEGER NOT NULL DEFAULT 1,
    parent_artifact_id UUID REFERENCES artifacts(id) ON DELETE SET NULL,
    manifest           JSONB,              -- generated by Python, never by a model
    jev_classification JSONB,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    metadata           JSONB NOT NULL DEFAULT '{}'::jsonb,
    search_tsv         TSVECTOR GENERATED ALWAYS AS
                         (to_tsvector('english', title || ' ' || coalesce(description,''))) STORED
);
CREATE UNIQUE INDEX IF NOT EXISTS artifacts_slug_version_key ON artifacts (slug, version);
CREATE INDEX IF NOT EXISTS artifacts_search_idx ON artifacts USING GIN (search_tsv);
CREATE INDEX IF NOT EXISTS artifacts_project_idx ON artifacts (project_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS artifacts_status_idx ON artifacts (storage_status, classification_status);
CREATE INDEX IF NOT EXISTS artifacts_conversation_idx ON artifacts (source_conversation_id);
DROP TRIGGER IF EXISTS artifacts_touch ON artifacts;
CREATE TRIGGER artifacts_touch BEFORE UPDATE ON artifacts
    FOR EACH ROW EXECUTE FUNCTION pc_touch_updated_at();

CREATE TABLE IF NOT EXISTS artifact_files (
    id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    artifact_id       UUID NOT NULL REFERENCES artifacts(id) ON DELETE CASCADE,
    relative_path     TEXT NOT NULL,       -- 'src/main.js' - sanitized, never absolute
    original_filename TEXT,
    mime_type         TEXT NOT NULL,
    extension         TEXT,
    byte_size         BIGINT NOT NULL,
    sha256            TEXT NOT NULL,
    object_key        TEXT,                -- NULL when storage_status <> 'captured'
    storage_status    pc_storage_status NOT NULL DEFAULT 'referenced',
    version           INTEGER NOT NULL DEFAULT 1,
    parent_file_id    UUID REFERENCES artifact_files(id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    metadata          JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE UNIQUE INDEX IF NOT EXISTS artifact_files_path_key
    ON artifact_files (artifact_id, relative_path, version);
CREATE INDEX IF NOT EXISTS artifact_files_sha_idx ON artifact_files (sha256);
CREATE UNIQUE INDEX IF NOT EXISTS artifact_files_object_key_key
    ON artifact_files (object_key) WHERE object_key IS NOT NULL;
DROP TRIGGER IF EXISTS artifact_files_touch ON artifact_files;
CREATE TRIGGER artifact_files_touch BEFORE UPDATE ON artifact_files
    FOR EACH ROW EXECUTE FUNCTION pc_touch_updated_at();

CREATE TABLE IF NOT EXISTS artifact_relationships (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    artifact_id     UUID NOT NULL REFERENCES artifacts(id) ON DELETE CASCADE,
    relation        TEXT NOT NULL,
        -- revision_of | derived_from | generated_from | belongs_to_project |
        -- related_to_note | related_to_conversation | part_of
    target_type     TEXT NOT NULL,   -- artifact | project | note | conversation | message
    target_id       UUID NOT NULL,
    relationship_status TEXT NOT NULL DEFAULT 'confirmed',  -- confirmed | uncertain
    provenance      pc_provenance NOT NULL DEFAULT 'system',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    metadata        JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE UNIQUE INDEX IF NOT EXISTS artifact_relationships_key
    ON artifact_relationships (artifact_id, relation, target_type, target_id);
CREATE INDEX IF NOT EXISTS artifact_relationships_target_idx
    ON artifact_relationships (target_type, target_id);

CREATE TABLE IF NOT EXISTS artifact_classifications (
    id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    artifact_id       UUID NOT NULL REFERENCES artifacts(id) ON DELETE CASCADE,
    semantic_category TEXT,
    project_id        UUID REFERENCES projects(id) ON DELETE SET NULL,
    promote_to_vault  BOOLEAN,
    needs_human_review BOOLEAN NOT NULL DEFAULT false,
    long_term_value   REAL,
    confidence        REAL,
    classifier        TEXT NOT NULL,       -- 'jev:jev-1.13.0' | 'rules'
    superseded        BOOLEAN NOT NULL DEFAULT false,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    metadata          JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS artifact_classifications_artifact_idx
    ON artifact_classifications (artifact_id, created_at DESC);

-- Original provider export archives. Restricted cold storage; never served.
CREATE TABLE IF NOT EXISTS source_documents (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    provider      TEXT NOT NULL REFERENCES providers(id),
    kind          TEXT NOT NULL DEFAULT 'provider_export',
    original_filename TEXT NOT NULL,
    byte_size     BIGINT NOT NULL,
    sha256        TEXT NOT NULL,
    object_key    TEXT,
    import_status TEXT NOT NULL DEFAULT 'pending',  -- pending|parsed|imported|failed
    conversation_count INTEGER NOT NULL DEFAULT 0,
    artifact_count     INTEGER NOT NULL DEFAULT 0,
    report        JSONB,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    metadata      JSONB NOT NULL DEFAULT '{}'::jsonb
);
-- Re-importing the same archive is a no-op, not a second copy of history.
CREATE UNIQUE INDEX IF NOT EXISTS source_documents_sha_key ON source_documents (sha256);
DROP TRIGGER IF EXISTS source_documents_touch ON source_documents;
CREATE TRIGGER source_documents_touch BEFORE UPDATE ON source_documents
    FOR EACH ROW EXECUTE FUNCTION pc_touch_updated_at();
