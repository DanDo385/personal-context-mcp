async def test_artifact_search_filters_by_capture_status(services) -> None:
    await services.artifacts.save_files(title="Captured thing", files={"a.txt": b"x"})
    await services.artifacts.register_reference(title="Referenced thing")

    captured = await services.artifacts.search(storage_status="captured")
    pending = await services.artifacts.search(storage_status="pending_import")
    assert [a.title for a in captured] == ["Captured thing"]
    assert [a.title for a in pending] == ["Referenced thing"]


async def test_attaching_to_a_project_records_a_relationship(services) -> None:
    project_id, _ = await services.projects.create(name="Personal AI Dashboard")
    record = await services.artifacts.save_files(title="Dashboard", files=WEB_PROJECT)
    await services.artifacts.attach_to_project(record.id, project_id)

    refreshed = await services.artifacts.get(record.id)
    assert refreshed.project == "personal-ai-dashboard"
    relation = await services.db.fetchval(
        """
        SELECT count(*) FROM artifact_relationships
        WHERE artifact_id = $1 AND relation = 'belongs_to_project'
        """,
        record.id,
    )
    assert relation == 1
