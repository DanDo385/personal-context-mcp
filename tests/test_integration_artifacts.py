async def test_revision_links_to_its_predecessor(services) -> None:
    first = await services.artifacts.save_files(title="Dashboard", files=WEB_PROJECT)
    second = await services.artifacts.create_revision(
        artifact_ref=str(first.id),
        files={**WEB_PROJECT, "index.html": b"<!doctype html><h1>v2</h1>"},
    )

    assert second.version == first.version + 1
    assert second.slug == first.slug
    assert second.id != first.id

    relation = await services.db.fetchrow(
        """
        SELECT relation, target_id FROM artifact_relationships
        WHERE artifact_id = $1 AND relation = 'revision_of'
        """,
        second.id,
    )
    assert relation["target_id"] == first.id


async def test_duplicate_bytes_are_detected_by_hash(services) -> None:
    first = await services.artifacts.save_files(title="A", files={"a.txt": b"identical"})
    sha = first.files[0].sha256
    assert await services.artifacts.find_by_hash(sha) == first.id


async def test_reference_is_never_reported_as_captured(services) -> None:
    """Acceptance test 4: metadata only, and honest about it."""
    record = await services.artifacts.register_reference(
        title="photo.jpg",
        description="An image the user uploaded in the native app.",
        artifact_type="image",
        expected_files=[{"filename": "photo.jpg", "byte_size": 204_800}],
    )

    assert record.storage_status == "pending_import"
    assert "NOT captured" in record.capture_note
    assert record.files[0].storage_status == "pending_import"
    # No hash, because there were no bytes to hash. An empty string would
    # look like a real value in a manifest.
    assert record.files[0].sha256 == ""


