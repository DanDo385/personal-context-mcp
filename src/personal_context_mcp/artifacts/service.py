"""Artifacts: capture, versioning, manifests, retrieval.

The central honesty rule of this module: ``storage_status`` is set to
``captured`` in exactly one place - after the bytes have been written to
object storage AND their SHA-256 matched what we computed before the write.
Everything else is ``referenced`` or ``pending_import``, and every tool that
reports on an artifact reports that status verbatim.

A compound artifact (a web project, a repo tree) is one ``artifacts`` row with
many ``artifact_files`` rows. Revisions bump the version and link back to the
previous artifact, rather than creating an unrelated duplicate.
"""

from __future__ import annotations

import json
from typing import Any
from uuid import UUID

import asyncpg

from personal_context_mcp.artifacts.keys import artifact_prefix, object_key, sanitize_relative_path
from personal_context_mcp.artifacts.manifest import MANIFEST_FILENAME, build_manifest
from personal_context_mcp.classifier.rules import detect_artifact_type
from personal_context_mcp.config import Settings
from personal_context_mcp.db.pool import Database
from personal_context_mcp.errors import IntegrityError, NotFoundError, ValidationError
from personal_context_mcp.logging_setup import get_logger
from personal_context_mcp.models import ArtifactFileRecord, ArtifactRecord
from personal_context_mcp.storage.base import ObjectStore
from personal_context_mcp.util import guess_mime, sha256_bytes, slugify

logger = get_logger(__name__)


def _file_record(row: asyncpg.Record) -> ArtifactFileRecord:
    return ArtifactFileRecord(
        relative_path=row["relative_path"],
        mime_type=row["mime_type"],
        byte_size=row["byte_size"],
        sha256=row["sha256"],
        storage_status=row["storage_status"],
        original_filename=row["original_filename"],
    )


def _artifact_record(row: asyncpg.Record, files: list[asyncpg.Record]) -> ArtifactRecord:
    captured = row["storage_status"] == "captured"
    return ArtifactRecord(
        id=row["id"],
        slug=row["slug"],
        title=row["title"],
        description=row["description"],
        artifact_type=row["artifact_type"],
        source_type=row["source_type"],
        source_provider=row["source_provider"],
        project=row.get("project_slug"),
        storage_status=row["storage_status"],
        classification_status=row["classification_status"],
        version=row["version"],
        file_count=len(files),
        total_bytes=sum(f["byte_size"] for f in files),
        created_at=row["created_at"],
        files=[_file_record(f) for f in files],
        capture_note=(
            "Bytes stored and SHA-256 verified."
            if captured
            else (
                "Metadata only. The bytes were NOT captured - this record notes "
                "that the artifact existed, nothing more."
            )
        ),
    )


class ArtifactService:
    def __init__(self, db: Database, store: ObjectStore, settings: Settings) -> None:
        self._db = db
        self._store = store
        self._settings = settings

    # ----------------------------------------------------------- creation

    async def save_files(
        self,
        *,
        title: str,
        files: dict[str, bytes],
        description: str | None = None,
        project_id: UUID | None = None,
        project_slug: str | None = None,
        source_provider: str | None = None,
        source_type: str = "generated_by_model",
        source_conversation_id: UUID | None = None,
        source_message_id: UUID | None = None,
        sensitivity: str = "normal",
        artifact_type: str | None = None,
        semantic_category: str | None = None,
        parent_artifact_id: UUID | None = None,
        version: int | None = None,
        slug: str | None = None,
        original_names: dict[str, str] | None = None,
    ) -> ArtifactRecord:
        """Store a set of files as ONE artifact, preserving the directory tree."""
        if not files:
            raise ValidationError("An artifact needs at least one file.")
        if len(files) > self._settings.max_bundle_files:
            raise ValidationError(
                f"{len(files)} files exceeds the limit of "
                f"{self._settings.max_bundle_files} per artifact."
            )

        # Sanitise every path first, so a bad one fails before anything is
        # written rather than halfway through.
        normalized: dict[str, bytes] = {}
        for raw_path, data in files.items():
            safe_path = sanitize_relative_path(raw_path)
            if safe_path == MANIFEST_FILENAME:
                raise ValidationError(
                    f"{MANIFEST_FILENAME} is generated by this service and cannot be supplied."
                )
            if len(data) > self._settings.max_artifact_file_bytes:
                raise ValidationError(
                    f"{safe_path} is {len(data)} bytes, above the per-file limit of "
                    f"{self._settings.max_artifact_file_bytes}."
                )
            normalized[safe_path] = data

        total = sum(len(d) for d in normalized.values())
        if total > self._settings.max_bundle_bytes:
            raise ValidationError(
                f"Artifact totals {total} bytes, above the limit of "
                f"{self._settings.max_bundle_bytes}."
            )

        base_slug = slugify(slug or title, fallback="artifact")
        resolved_type = artifact_type or detect_artifact_type(list(normalized))
        resolved_version = version or await self._next_version(base_slug)

        prefix = artifact_prefix(
            artifact_slug=base_slug,
            version=resolved_version,
            project_slug=project_slug,
            semantic_category=semantic_category,
            artifact_type=resolved_type,
        )

        artifact_id = await self._db.fetchval(
            """
            INSERT INTO artifacts (
                slug, title, description, artifact_type, source_type, source_provider,
                source_conversation_id, source_message_id, project_id, storage_status,
                sensitivity, storage_prefix, version, parent_artifact_id
            ) VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9,'referenced',$10::pc_sensitivity,
                      $11,$12,$13)
            RETURNING id
            """,
            base_slug,
            title.strip(),
            description,
            resolved_type,
            source_type,
            source_provider,
            source_conversation_id,
            source_message_id,
            project_id,
            sensitivity,
            prefix,
            resolved_version,
            parent_artifact_id,
        )

        stored_rows: list[dict[str, Any]] = []
        for relative_path, data in sorted(normalized.items()):
            digest = sha256_bytes(data)
            mime = guess_mime(relative_path)
            key = object_key(prefix, relative_path)

            stored = await self._store.put(key, data, mime_type=mime)
            # Verify what came back, not what we intended to send.
            if stored.sha256 != digest:
                raise IntegrityError(
                    f"Stored bytes for {relative_path} did not match the expected hash."
                )

            await self._db.execute(
                """
                INSERT INTO artifact_files (
                    artifact_id, relative_path, original_filename, mime_type, extension,
                    byte_size, sha256, object_key, storage_status, version
                ) VALUES ($1,$2,$3,$4,$5,$6,$7,$8,'captured',$9)
                """,
                artifact_id,
                relative_path,
                (original_names or {}).get(relative_path),
                mime,
                "." + relative_path.rsplit(".", 1)[-1].lower() if "." in relative_path else None,
                len(data),
                digest,
                key,
                resolved_version,
            )
            stored_rows.append(
                {
                    "relative_path": relative_path,
                    "sha256": digest,
                    "mime_type": mime,
                    "byte_size": len(data),
                    "storage_status": "captured",
                    "original_filename": (original_names or {}).get(relative_path),
                }
            )

        await self._write_manifest(
            artifact_id=artifact_id,
            slug=base_slug,
            title=title,
            description=description,
            artifact_type=resolved_type,
            source_provider=source_provider,
            source_conversation_id=source_conversation_id,
            project_slug=project_slug,
            version=resolved_version,
            prefix=prefix,
            files=stored_rows,
        )

        # Only now, with every byte written and verified, is it "captured".
        await self._db.execute(
            "UPDATE artifacts SET storage_status = 'captured' WHERE id = $1", artifact_id
        )

        if parent_artifact_id:
            await self.relate(
                artifact_id,
                relation="revision_of",
                target_type="artifact",
                target_id=parent_artifact_id,
            )
        if source_conversation_id:
            await self.relate(
                artifact_id,
                relation="related_to_conversation",
                target_type="conversation",
                target_id=source_conversation_id,
            )
        if project_id:
            await self.relate(
                artifact_id,
                relation="belongs_to_project",
                target_type="project",
                target_id=project_id,
            )

        logger.info(
            "artifact captured",
            extra={"artifact_id": str(artifact_id), "file_count": len(stored_rows)},
        )
        record = await self.get(artifact_id)
        assert record is not None
        return record

    async def register_reference(
        self,
        *,
        title: str,
        description: str | None = None,
        status: str = "pending_import",
        artifact_type: str = "other",
        source_provider: str | None = None,
        source_type: str = "uploaded_by_user",
        source_conversation_id: UUID | None = None,
        project_id: UUID | None = None,
        expected_files: list[dict[str, Any]] | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> ArtifactRecord:
        """Record that an artifact existed without claiming we captured it.

        Used when a provider shows the model a file it cannot hand to a tool.
        The row is deliberately marked ``referenced`` / ``pending_import`` so
        a later export import can fill in the bytes.
        """
        if status not in ("referenced", "pending_import"):
            raise ValidationError(
                "register_reference records artifacts whose bytes we do NOT have. "
                "Use artifact_save_text or artifact_save_bundle when you have content."
            )

        slug = slugify(title, fallback="artifact")

        # Captured artifacts deduplicate on SHA-256. A reference has no bytes
        # and therefore no hash, so it needs its own guard: the same filename
        # against the same conversation is the same missing file. Without
        # this, re-importing an export accumulates placeholder artifacts.
        if source_conversation_id is not None:
            existing = await self._db.fetchval(
                """
                SELECT id FROM artifacts
                WHERE slug = $1 AND source_conversation_id = $2
                  AND storage_status <> 'captured'
                LIMIT 1
                """,
                slug,
                source_conversation_id,
            )
            if existing is not None:
                record = await self.get(existing)
                if record is not None:
                    return record
        artifact_id = await self._db.fetchval(
            """
            INSERT INTO artifacts (
                slug, title, description, artifact_type, source_type, source_provider,
                source_conversation_id, project_id, storage_status, version, metadata
            ) VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9::pc_storage_status,
                      $10,$11)
            RETURNING id
            """,
            slug,
            title.strip(),
            description,
            artifact_type,
            source_type,
            source_provider,
            source_conversation_id,
            project_id,
            status,
            await self._next_version(slug),
            metadata or {},
        )
        for entry in expected_files or []:
            filename = str(entry.get("filename") or entry.get("path") or "unknown")
            await self._db.execute(
                """
                INSERT INTO artifact_files (
                    artifact_id, relative_path, original_filename, mime_type, extension,
                    byte_size, sha256, object_key, storage_status
                ) VALUES ($1,$2,$3,$4,$5,$6,$7,NULL,$8::pc_storage_status)
                """,
                artifact_id,
                sanitize_relative_path(filename),
                filename,
                entry.get("mime_type") or guess_mime(filename),
                "." + filename.rsplit(".", 1)[-1].lower() if "." in filename else None,
                int(entry.get("byte_size") or 0),
                # No bytes, so no hash. An empty string would look like one.
                entry.get("sha256") or "",
                status,
            )
        record = await self.get(artifact_id)
        assert record is not None
        return record

    async def _next_version(self, slug: str) -> int:
        current = await self._db.fetchval(
            "SELECT max(version) FROM artifacts WHERE slug = $1", slug
        )
        return int(current or 0) + 1

    async def _write_manifest(
        self,
        *,
        artifact_id: UUID,
        slug: str,
        title: str,
        description: str | None,
        artifact_type: str,
        source_provider: str | None,
        source_conversation_id: UUID | None,
        project_slug: str | None,
        version: int,
        prefix: str,
        files: list[dict[str, Any]],
    ) -> dict[str, Any]:
        manifest = build_manifest(
            artifact_id=artifact_id,
            slug=slug,
            title=title,
            description=description,
            artifact_type=artifact_type,
            source_provider=source_provider,
            source_conversation_id=source_conversation_id,
            project_slug=project_slug,
            version=version,
            storage_status="captured",
            storage_prefix=prefix,
            files=files,
        )
        payload = json.dumps(manifest, indent=2, sort_keys=True).encode("utf-8")
        await self._store.put(
            object_key(prefix, MANIFEST_FILENAME), payload, mime_type="application/json"
        )
        await self._db.execute(
            "UPDATE artifacts SET manifest = $2 WHERE id = $1", artifact_id, manifest
        )
        return manifest

    async def create_revision(
        self,
        *,
        artifact_ref: str,
        files: dict[str, bytes],
        title: str | None = None,
        description: str | None = None,
    ) -> ArtifactRecord:
        """New version of an existing artifact, linked to its predecessor."""
        previous = await self._resolve_row(artifact_ref)
        return await self.save_files(
            title=title or previous["title"],
            description=description or previous["description"],
            files=files,
            slug=previous["slug"],
            version=previous["version"] + 1,
            project_id=previous["project_id"],
            project_slug=previous.get("project_slug"),
            source_provider=previous["source_provider"],
            source_type=previous["source_type"],
            source_conversation_id=previous["source_conversation_id"],
            sensitivity=previous["sensitivity"],
            artifact_type=previous["artifact_type"],
            parent_artifact_id=previous["id"],
        )

    # ------------------------------------------------------------- reading

    async def _resolve_row(self, reference: str) -> asyncpg.Record:
        try:
            artifact_uuid: UUID | None = UUID(str(reference))
        except (ValueError, AttributeError):
            artifact_uuid = None

        row = await self._db.fetchrow(
            """
            SELECT a.*, p.slug AS project_slug
            FROM artifacts a LEFT JOIN projects p ON p.id = a.project_id
            WHERE ($1::uuid IS NOT NULL AND a.id = $1::uuid) OR a.slug = $2
            ORDER BY ($1::uuid IS NOT NULL AND a.id = $1::uuid) DESC, a.version DESC
            LIMIT 1
            """,
            artifact_uuid,
            slugify(str(reference)),
        )
        if row is None:
            raise NotFoundError(
                f"No artifact matches {reference!r}. Use artifact_search to find it."
            )
        return row

    async def get(self, reference: str | UUID) -> ArtifactRecord | None:
        try:
            row = await self._resolve_row(str(reference))
        except NotFoundError:
            return None
        files = await self._db.fetch(
            """
            SELECT * FROM artifact_files
            WHERE artifact_id = $1 AND version = (
                SELECT version FROM artifacts WHERE id = $1
            )
            ORDER BY relative_path
            """,
            row["id"],
        )
        return _artifact_record(row, list(files))

    async def manifest(self, reference: str) -> dict[str, Any]:
        row = await self._resolve_row(reference)
        if row["manifest"]:
            return dict(row["manifest"])
        files = await self._db.fetch(
            "SELECT * FROM artifact_files WHERE artifact_id = $1 ORDER BY relative_path",
            row["id"],
        )
        return build_manifest(
            artifact_id=row["id"],
            slug=row["slug"],
            title=row["title"],
            description=row["description"],
            artifact_type=row["artifact_type"],
            source_provider=row["source_provider"],
            source_conversation_id=row["source_conversation_id"],
            project_slug=row.get("project_slug"),
            version=row["version"],
            storage_status=row["storage_status"],
            storage_prefix=row["storage_prefix"],
            files=[dict(f) for f in files],
        )

    async def search(
        self,
        query: str = "",
        *,
        limit: int = 20,
        project_id: UUID | None = None,
        artifact_type: str | None = None,
        provider: str | None = None,
        storage_status: str | None = None,
    ) -> list[ArtifactRecord]:
        rows = await self._db.fetch(
            """
            SELECT a.*, p.slug AS project_slug,
                   CASE WHEN $1 = '' THEN 0
                        ELSE ts_rank_cd(a.search_tsv, websearch_to_tsquery('english', $1))
                   END AS rank
            FROM artifacts a LEFT JOIN projects p ON p.id = a.project_id
            WHERE ($1 = '' OR a.search_tsv @@ websearch_to_tsquery('english', $1)
                           OR a.title ILIKE '%' || $1 || '%')
              AND ($2::uuid IS NULL OR a.project_id = $2)
              AND ($3::text IS NULL OR a.artifact_type = $3)
              AND ($4::text IS NULL OR a.source_provider = $4)
              AND ($5::text IS NULL OR a.storage_status = $5::pc_storage_status)
            ORDER BY rank DESC, a.created_at DESC
            LIMIT $6
            """,
            query,
            project_id,
            artifact_type,
            provider,
            storage_status,
            limit,
        )
        results: list[ArtifactRecord] = []
        for row in rows:
            files = await self._db.fetch(
                "SELECT * FROM artifact_files WHERE artifact_id = $1 ORDER BY relative_path",
                row["id"],
            )
            results.append(_artifact_record(row, list(files)))
        return results

    async def find_by_hash(self, sha256: str) -> UUID | None:
        """Exact-duplicate detection, by content not by name."""
        return await self._db.fetchval(
            "SELECT artifact_id FROM artifact_files WHERE sha256 = $1 LIMIT 1", sha256
        )

    async def signed_download(
        self, *, artifact_ref: str, relative_path: str | None = None
    ) -> list[dict[str, Any]]:
        row = await self._resolve_row(artifact_ref)
        if row["storage_status"] != "captured":
            raise ValidationError(
                f"Artifact {row['slug']!r} has status {row['storage_status']}: its bytes "
                "were never captured, so there is nothing to download."
            )
        files = await self._db.fetch(
            """
            SELECT relative_path, object_key, mime_type, byte_size, sha256
            FROM artifact_files
            WHERE artifact_id = $1 AND object_key IS NOT NULL
              AND ($2::text IS NULL OR relative_path = $2)
            ORDER BY relative_path
            """,
            row["id"],
            relative_path,
        )
        if not files:
            raise NotFoundError("No captured files match that path.")

        ttl = (
            self._settings.signed_url_ttl_sensitive_seconds
            if row["sensitivity"] != "normal"
            else self._settings.signed_url_ttl_seconds
        )
        out = []
        for f in files:
            out.append(
                {
                    "relative_path": f["relative_path"],
                    "mime_type": f["mime_type"],
                    "byte_size": f["byte_size"],
                    "sha256": f["sha256"],
                    "url": await self._store.signed_download_url(f["object_key"], expires_in=ttl),
                    "expires_in_seconds": ttl,
                }
            )
        return out

    # -------------------------------------------------------- relationships

    async def relate(
        self,
        artifact_id: UUID,
        *,
        relation: str,
        target_type: str,
        target_id: UUID,
        relationship_status: str = "confirmed",
        provenance: str = "system",
    ) -> None:
        await self._db.execute(
            """
            INSERT INTO artifact_relationships (
                artifact_id, relation, target_type, target_id, relationship_status,
                provenance
            ) VALUES ($1,$2,$3,$4,$5,$6::pc_provenance)
            ON CONFLICT (artifact_id, relation, target_type, target_id) DO NOTHING
            """,
            artifact_id,
            relation,
            target_type,
            target_id,
            relationship_status,
            provenance,
        )

    async def attach_to_project(self, artifact_id: UUID, project_id: UUID) -> None:
        await self._db.execute(
            "UPDATE artifacts SET project_id = $2 WHERE id = $1", artifact_id, project_id
        )
        await self.relate(
            artifact_id,
            relation="belongs_to_project",
            target_type="project",
            target_id=project_id,
        )

    async def record_classification(
        self,
        artifact_id: UUID,
        *,
        semantic_category: str | None,
        project_id: UUID | None,
        promote_to_vault: bool | None,
        needs_human_review: bool,
        long_term_value: float | None,
        confidence: float | None,
        classifier: str,
        answers: dict[str, Any],
    ) -> UUID | None:
        await self._db.execute(
            """
            UPDATE artifact_classifications SET superseded = true
            WHERE artifact_id = $1 AND superseded = false
            """,
            artifact_id,
        )
        classification_id = await self._db.fetchval(
            """
            INSERT INTO artifact_classifications (
                artifact_id, semantic_category, project_id, promote_to_vault,
                needs_human_review, long_term_value, confidence, classifier, metadata
            ) VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9)
            RETURNING id
            """,
            artifact_id,
            semantic_category,
            project_id,
            promote_to_vault,
            needs_human_review,
            long_term_value,
            confidence,
            classifier,
            {"answers": answers},
        )
        await self._db.execute(
            """
            UPDATE artifacts
            SET classification_status = $2::pc_classification_status,
                jev_classification = $3
            WHERE id = $1
            """,
            artifact_id,
            "needs_review" if needs_human_review else "classified",
            {"answers": answers, "category": semantic_category},
        )
        return classification_id

    async def files_for_mirror(self, artifact_id: UUID, *, max_bytes: int) -> list[dict[str, Any]]:
        """Files small enough to mirror into the vault as real files."""
        rows = await self._db.fetch(
            """
            SELECT relative_path, object_key, mime_type, byte_size, sha256
            FROM artifact_files
            WHERE artifact_id = $1 AND storage_status = 'captured'
              AND object_key IS NOT NULL AND byte_size <= $2
            ORDER BY relative_path
            """,
            artifact_id,
            max_bytes,
        )
        return [dict(r) for r in rows]
