"""Object storage abstraction.

Two implementations: Supabase Storage (the v1 default) and a local filesystem
backend used by tests and by anyone who wants to run without a cloud bucket.

Object keys are ALWAYS generated by :mod:`personal_context_mcp.artifacts.keys`.
No model, and no classifier, ever supplies a path to these methods.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol, runtime_checkable


@dataclass(frozen=True)
class StoredObject:
    object_key: str
    byte_size: int
    sha256: str
    mime_type: str


@dataclass(frozen=True)
class UploadTicket:
    """A pre-authorised direct upload, so bytes never transit a tool argument."""

    object_key: str
    upload_url: str
    method: str
    headers: dict[str, str]
    expires_in: int


@runtime_checkable
class ObjectStore(Protocol):
    bucket: str

    async def put(
        self, object_key: str, data: bytes, *, mime_type: str, bucket: str | None = None
    ) -> StoredObject: ...

    async def get(self, object_key: str, *, bucket: str | None = None) -> bytes: ...

    async def delete(self, object_key: str, *, bucket: str | None = None) -> None: ...

    async def exists(self, object_key: str, *, bucket: str | None = None) -> bool: ...

    async def signed_download_url(
        self, object_key: str, *, expires_in: int, bucket: str | None = None
    ) -> str: ...

    async def signed_upload_ticket(
        self, object_key: str, *, mime_type: str, expires_in: int, bucket: str | None = None
    ) -> UploadTicket: ...

    async def aclose(self) -> None: ...
